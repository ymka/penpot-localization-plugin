"""Assemble the Penpot adapter into the classic script named in the manifest."""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    "src/translation-validation.js",
    "src/rtl-metadata.js",
    "src/plugin.js",
)
OUTPUT = ROOT / "plugin/plugin.js"
BUILD_COMMAND = "python3 scripts/build_plugin.py"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the checked-in script needs regeneration")
    args = parser.parse_args()

    sections = [f"// Generated by {BUILD_COMMAND}. Edit the files in src/."]
    for source in SOURCES:
        code = (ROOT / source).read_text(encoding="utf-8").rstrip("\n")
        sections.append(f"// {source}\n{code}")
    script = "\n\n".join(sections) + "\n"

    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != script:
            parser.exit(1, f"plugin/plugin.js is out of date. Run {BUILD_COMMAND}.\n")
    else:
        OUTPUT.write_bytes(script.encode("utf-8"))


if __name__ == "__main__":
    main()
